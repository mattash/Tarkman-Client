const fs = require('node:fs')
const path = require('node:path')
const { IOSConfig, withAppDelegate, withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins')

// Apps linked against the tvOS/iOS 27 SDK must adopt the UIScene lifecycle: UIKit traps at launch
// (_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption) otherwise. Expo SDK 57's template
// still creates its window in the app delegate, so this plugin moves window creation into a
// SceneDelegate. Remove it once the Expo template adopts scenes itself.
const SCENE_DELEGATE = `import React
import UIKit

// Generated by plugins/withSceneLifecycle.js. React Native starts in the scene's window.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else { return }
    let window = UIWindow(windowScene: windowScene)
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: nil)
    self.window = window
    appDelegate.window = window
  }
}
`
const LEGACY_WINDOW = /#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\(\n\s*withModuleName: "main",\n\s*in: window,\n\s*launchOptions: launchOptions\)\n#endif\n/

function withSceneLifecycle(config) {
  config = withInfoPlist(config, config => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [{
          UISceneConfigurationName: 'Default Configuration',
          UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
        }],
      },
    }
    return config
  })
  config = withAppDelegate(config, config => {
    if (config.modResults.language !== 'swift') throw new Error('withSceneLifecycle expects a Swift AppDelegate')
    const contents = config.modResults.contents
    if (!LEGACY_WINDOW.test(contents)) throw new Error('withSceneLifecycle: the Expo AppDelegate template changed; update the plugin or remove it if the template adopts scenes')
    config.modResults.contents = contents.replace(LEGACY_WINDOW, '    // The window and React Native root are created by SceneDelegate (plugins/withSceneLifecycle.js).\n')
    return config
  })
  config = withDangerousMod(config, ['ios', config => {
    const file = path.join(IOSConfig.Paths.getSourceRoot(config.modRequest.projectRoot), 'SceneDelegate.swift')
    fs.writeFileSync(file, SCENE_DELEGATE)
    return config
  }])
  return withXcodeProject(config, config => {
    const name = IOSConfig.XcodeUtils.getProjectName(config.modRequest.projectRoot)
    const filepath = `${name}/SceneDelegate.swift`
    if (!config.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: name, project: config.modResults })
    }
    return config
  })
}

module.exports = withSceneLifecycle
